#pragma once
#include "imu_core.h"

/* ============================================================================
 * MPU6050 · I2C 驱动层（薄层：总线 + 寄存器 + 日志）
 * ==========================================================================
 * 【分层】
 *   imu_core.*  : 纯算法（解析 / 轴映射 / 校准统计 / 互补滤波），可 PC 编译测试
 *   imu_driver.*: 本文件，只负责 I2C 收发、寄存器序列、错误日志、校准采样节奏
 *   分开的好处: 拿到 14 字节之后的每一步都能在电脑上用合成数据验证，
 *              硬件来了只剩"传感器准不准"这一个未知量。
 *
 * 【生命周期: 刻意不做幂等】
 *   imu_init()  无条件新建 I2C 总线 + 设备（端口已被占用会返回 ESP_ERR_INVALID_STATE）
 *   imu_deinit() 拆除设备与总线，并把句柄置空
 *   因此每条退出路径（正常结束 / 提前 return / 按 x 中止）都必须走到 imu_deinit()，
 *   否则下一轮 imu_init() 必然失败。这是「对称式」写法换来的简单，代价是纪律。
 *
 * 【驱动三步（缺一不可）】
 *   ① 验身份: 读 WHO_AM_I(0x75) 应为 0x68 —— 不验就不知道接没接对
 *   ② 唤醒:   写 PWR_MGMT_1(0x6B) = 0x00 —— 不唤醒读回来全是 0
 *   ③ 连读:   从 ACCEL_XOUT_H(0x3B) 连读 14 字节（加速度 6 + 温度 2 + 陀螺 6）
 *
 * 【量程与系数成对改】
 *   加速度 ±2 g → 16384 LSB/g；陀螺 ±250 °/s → 131 LSB/(°/s)（在 imu_core.h）
 *   改一个不改另一个 = 角度整体错倍数，而且能编译、跑起来"看起来在动"。
 *
 * 【坐标系（第4课车体坐标约定）】
 *   车体: +x 车头朝前、+y 车身左侧、+z 垂直向上（右手系）
 *   实测验证法（三问）:
 *     车头抬起 → pitch 应增大; 左侧抬起 → roll 应增大; 俯视逆时针转 → yaw 应增大
 *   任一项反了，改 IMU_AXIS_* 这张表，不要改 imu_core.cpp 的解算公式。
 * ========================================================================== */

/* 总线 + 设备 + 验身份 + 唤醒。成功返回 true；
 * 失败时已创建的资源不自动回收，调用方仍需 imu_deinit()（保证下一次能重建）。 */
bool imu_init();

/* 拆除设备与总线并置空句柄；未创建时是空操作 */
void imu_deinit();

/* 读一帧 14 字节并换算。失败返回 false（I2C 无应答/超时），不修改输出 */
bool imu_read_raw(ImuRaw& out);

/* 静置求陀螺零偏: 连续采样 samples 次取均值，同时统计标准差作噪声底。
 * 耗时约 1.5 s（采样间让出 CPU），短于框架 3 s 中止宽限，故内部不查中止标志。
 * 调用前必须让小车静止、且已上电预热数分钟（零偏随温度漂）。 */
bool imu_calibrate(int samples = 1000);

/* 采一帧 → 扣零偏 → 互补滤波推进一次。dt_s 为距上次调用的真实间隔（秒）。
 * 返回 false 表示本帧读取失败（本帧跳过，姿态保持上一次的值）。 */
bool imu_update(float dt_s);

const ImuAttitude& imu_attitude();          // 当前姿态
void imu_get_bias(float out[3]);            // 当前零偏 °/s（未校准时全 0）
const ImuRaw& imu_raw();                    // 最近一帧原始物理量（1.17 猛拍峰值用）

/* ---------------- 诊断辅助（2026-11-11 增，只增不改既有逻辑） ---------------- */

/* 连读 WHO_AM_I n 次，返回失败次数（采集单"连读100次"格用）；n<=0 返回 -1 */
int imu_whoami_sweep(int n);

/* 强制睡眠/唤醒演示: 写 PWR_MGMT_1=0x40 睡眠 → 读 ACCEL_XOUT 两字节(应 0x00)
 * → 写回 0x00 唤醒 → 再读两字节(应非零)。out_sleep/out_wake 带回读数。
 * 返回 false 表示 I2C 出错。演示结束器件处于唤醒态。 */
bool imu_sleep_wake_demo(uint8_t out_sleep[2], uint8_t out_wake[2]);
